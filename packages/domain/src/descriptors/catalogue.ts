export interface SeedValue {
  code: string;
  en: string;
  ar: string;
  meaning?: string;
  oneroster?: string;
  /** Ed-Fi code value within the namespace's descriptor. */
  edfi?: string;
  /** Staff and contact identification code value, for `external_id_system`. */
  edfiStaffContact?: string;
}

export interface SeedNamespace {
  namespace: string;
  /** Schools may add values. */
  open: boolean;
  /** Every value carries a fixed `system_meaning`. */
  meaningRequired: boolean;
  /** The Ed-Fi descriptor a value's `edfi` code belongs to. */
  edfiDescriptor?: string;
  values: readonly SeedValue[];
}

